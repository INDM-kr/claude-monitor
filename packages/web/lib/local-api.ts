import { getProcessCollector } from "@claude-monitor/collector";
import { checkBearer, unauthorized } from "./auth/middleware";

const BODY_LIMIT = 16_384;
const LOOPBACK_HOSTS = new Set(["127.0.0.1", "localhost", "[::1]", "0.0.0.0"]);
const headers = { "cache-control": "no-store" };
const inputErrors = new Set(["invalid_input", "invalid_text", "required_text", "invalid_artifact_reference", "invalid_retention", "invalid_cutoff", "invalid_label", "invalid_project", "human_confirmation_required", "artifact_required", "purge_confirmation_required", "purge_backup_required", "project_not_empty", "invalid_merge", "invalid_candidate"]);
const conflictErrors = new Set(["reopen_before_editing", "work_not_verified", "purge_preview_changed"]);

export async function localRead(request: Request, method: string): Promise<Response> {
  if (!checkBearer(request).ok) return unauthorized();
  return call(method);
}

export async function localWrite(request: Request, allowed: Record<string, string>): Promise<Response> {
  if (!checkBearer(request).ok) return unauthorized();
  // Browsers cannot mutate this local service from a different origin, even with no Bearer configured.
  const origin = request.headers.get("origin");
  const url = new URL(request.url), host = request.headers.get("host") ?? url.host;
  let sameOrigin = true;
  try { sameOrigin = LOOPBACK_HOSTS.has(new URL(`${url.protocol}//${host}`).hostname); }
  catch { sameOrigin = false; }
  if (origin) {
    try { const source = new URL(origin); sameOrigin = sameOrigin && source.host === host && source.protocol === url.protocol; }
    catch { sameOrigin = false; }
  }
  if (!sameOrigin || request.headers.get("sec-fetch-site") === "cross-site") return Response.json({ error: "origin_rejected" }, { status: 403, headers });
  if (!request.headers.get("content-type")?.startsWith("application/json")) return Response.json({ error: "json_required" }, { status: 415, headers });
  let payload: Record<string, unknown>;
  try {
    const body = await request.text();
    if (body.length > BODY_LIMIT) return Response.json({ error: "body_too_large" }, { status: 413, headers });
    const parsed = JSON.parse(body);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("invalid");
    payload = parsed;
  } catch { return Response.json({ error: "invalid_json" }, { status: 400, headers }); }
  const action = typeof payload.action === "string" ? payload.action : "";
  if (!Object.prototype.hasOwnProperty.call(allowed, action)) return Response.json({ error: "invalid_action" }, { status: 400, headers });
  // Backup names are generated by the writer after creating a snapshot, never supplied by clients.
  const { action: _, backupName: __, ...values } = payload;
  return call(allowed[action]!, values);
}

async function call(method: string, payload?: unknown): Promise<Response> {
  try { return Response.json(await getProcessCollector().request(method, payload), { headers }); }
  catch (error) {
    const code = error instanceof Error ? ((error as Error & { code?: string }).code ?? error.message) : "collector_unavailable";
    if (inputErrors.has(code)) return Response.json({ error: code }, { status: 400, headers });
    if (conflictErrors.has(code)) return Response.json({ error: code }, { status: 409, headers });
    if (["work_not_found", "run_not_found", "project_not_found", "unknown_project", "unknown_workspace"].includes(code)) return Response.json({ error: code }, { status: 404, headers });
    return Response.json({ error: "collector_unavailable" }, { status: 503, headers });
  }
}
